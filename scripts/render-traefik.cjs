#!/usr/bin/env node
// Renders infra/traefik/traefik.yml (static config) from backend/.env.
// Traefik's static config cannot read env vars from a file, so ports are baked in here.
// The dynamic config (infra/traefik/dynamic/*.yml) uses Traefik's own {{ env }} templating.
const fs = require('fs');
const path = require('path');
const { ROOT, loadEnv } = require('./lib/env.cjs');

function render() {
  const e = loadEnv();
  const yml = `# GENERATED by scripts/render-traefik.cjs from backend/.env — do not edit.
global:
  checkNewVersion: false
  sendAnonymousUsage: false

entryPoints:
  web:
    address: ":${e.GATEWAY_HTTP_PORT}"
    http:
      redirections:
        entryPoint:
          to: websecure
          scheme: https
  websecure:
    address: ":${e.GATEWAY_HTTPS_PORT}"
    http:
      tls: {}
    transport:
      respondingTimeouts:
        readTimeout: 120s
  internal:
    address: "${e.GATEWAY_INTERNAL_BIND}:${e.GATEWAY_INTERNAL_PORT}"
  traefik:
    # dashboard + API are unauthenticated: only on this machine by default
    address: "${e.GATEWAY_DASHBOARD_BIND || '127.0.0.1'}:${e.GATEWAY_DASHBOARD_PORT}"

api:
  dashboard: true
  insecure: true

ping:
  entryPoint: traefik

providers:
  providersThrottleDuration: 1s
  file:
    directory: "${path.join(ROOT, 'infra', 'traefik', 'dynamic')}"
    watch: true
  redis:
    endpoints:
      - "${e.REDIS_HOST}:${e.REDIS_PORT}"
    rootKey: traefik
    db: ${e.REDIS_REGISTRY_DB || 0}

log:
  level: INFO

accessLog:
  bufferingSize: 50
`;
  const out = path.join(ROOT, 'infra', 'traefik', 'traefik.yml');
  fs.writeFileSync(out, yml);
  return out;
}

if (require.main === module) {
  console.log('wrote ' + render());
}

module.exports = { render };
